"""Alembic environment.

Master rules section 67: schema changes only ever happen through a reviewed,
version-controlled migration. The database URL comes from application settings
rather than ``alembic.ini`` so credentials are never committed.

Migrations run over the *synchronous* driver (psycopg) deliberately: Alembic's
autogenerate and offline modes are synchronous, and mixing an async engine in
adds moving parts to the one operation that must be predictable.
"""

from __future__ import annotations

import sys
from logging.config import fileConfig
from pathlib import Path

from alembic import context
from sqlalchemy import engine_from_config, pool

# Make the application importable when Alembic is invoked from apps/api.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.core.config import settings  # noqa: E402
from src.core.registry import get_metadata  # noqa: E402

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

config.set_main_option("sqlalchemy.url", settings.database_sync_url)

# Importing every module's models is what makes autogenerate see the full schema.
target_metadata = get_metadata()


def include_object(obj, name, type_, reflected, compare_to):  # type: ignore[no-untyped-def]
    """Keep objects Alembic should not manage out of autogenerate.

    ``pg_stat_statements`` and other extension-owned relations are reflected but
    are not ours; without this filter every autogenerated migration tries to
    drop them.
    """
    if type_ == "table" and name in {"pg_stat_statements", "pg_stat_statements_info"}:
        return False
    if type_ == "index" and name and name.startswith("pg_"):
        return False
    return True


def process_revision_directives(context_, revision, directives):  # type: ignore[no-untyped-def]
    """Do not write an empty migration when nothing changed."""
    if getattr(config.cmd_opts, "autogenerate", False) and directives:
        script = directives[0]
        if script.upgrade_ops.is_empty():
            directives[:] = []
            print("No schema changes detected - nothing to generate.")  # noqa: T201


def run_migrations_offline() -> None:
    """Emit SQL without a database connection, for review before applying."""
    context.configure(
        url=settings.database_sync_url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        compare_type=True,
        compare_server_default=True,
        include_object=include_object,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Apply migrations against a live database."""
    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )

    with connectable.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            # compare_type catches a Numeric(18,4) silently becoming Numeric(10,2),
            # which would quietly truncate money.
            compare_type=True,
            compare_server_default=True,
            include_object=include_object,
            process_revision_directives=process_revision_directives,
            transaction_per_migration=True,
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
