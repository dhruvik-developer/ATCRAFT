#: Stand-in for NULL in the balance grain's unique index. The nil UUID is not a
#: valid id anywhere in the system, so it cannot collide with a real location or
#: batch, and COALESCE-ing to it makes "no location" a single indexable value
#: instead of an unenforceable NULL.
GRAIN_NULL_SENTINEL = "00000000-0000-0000-0000-000000000000"

#: The ON CONFLICT target of the balance upsert, and the definition of the
#: unique index below. Written once so the two can never disagree - a mismatch
#: makes PostgreSQL fail to infer the index at runtime, not at deploy time.
BALANCE_GRAIN_SQL = (
    "company_id, item_id, warehouse_id, "
    f"coalesce(location_id, '{GRAIN_NULL_SENTINEL}'::uuid), "
    f"coalesce(batch_id, '{GRAIN_NULL_SENTINEL}'::uuid)"
)


class TransactionType(StrEnum):
    """The movement vocabulary from master rules section 83.

    Every member has a fixed sign (:data:`TRANSACTION_SIGNS`). The sign is a
    property of the *type*, never of the caller's arithmetic: a receipt that
    arrives with a negative quantity is a mis-keyed document, not a clever way
    to express an issue.
    """

