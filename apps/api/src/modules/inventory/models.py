class CostLayerPool(StrEnum):
    """Which of a position's two FIFO queues a cost layer belongs to.

    ``ON_HAND`` is the queue the whole valuation rests on: its open layers add
    up to ``on_hand_quantity`` and to ``stock_value``. ``SCRAP`` remembers what
    the stock now standing in ``scrap_quantity`` cost when it was scrapped, so a
    scrap disposal can be valued from the layers it consumes rather than from
    whatever usable stock happens to remain beside it. Scrap carries no book
    value - the scrapping movement already charged its cost - so the ``SCRAP``
    queue is never part of ``stock_value`` or of any valuation total.
    """

    ON_HAND = "ON_HAND"
    SCRAP = "SCRAP"


class StatusEnum(TypeDecorator[Any]):
    """A ``VARCHAR`` status column that comes back as its :class:`StrEnum` member.

    Mapping a plain ``String`` column to ``Mapped[SomeStatus]`` stores the value
    correctly but returns a bare ``str`` on read. The result is that
    ``document.status is Status.DRAFT`` is True for an object still in memory and
    False for the same row loaded from the database - an asymmetry that produces
    a bug the first time a rule is written with ``is`` instead of ``==``, and
    that only shows up on the second request.

    Converting on the way out removes the whole class of mistake, and the DDL is
    unchanged: this is still ``VARCHAR(n)`` with the values a ``StrEnum``
    produces, exactly as the database contract specifies.
    """

    impl = String
    cache_ok = True

    def __init__(self, enum_class: type[StrEnum], length: int = 24) -> None:
        super().__init__(length=length)
        # Named to match the constructor argument: SQLAlchemy builds this type's
        # statement-cache key from constructor kwargs, so an attribute it cannot
        # see would let two different status enums share one cache entry.
        self.enum_class = enum_class

    def process_bind_param(self, value: Any, dialect: Any) -> str | None:
        return None if value is None else str(value)

    def process_result_value(self, value: Any, dialect: Any) -> Any:
        return None if value is None else self.enum_class(value)


