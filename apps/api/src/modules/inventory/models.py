"""Inventory engine tables - the correctness floor of the whole system.

Master rules section 10 ranks inventory correctness above every performance
goal, and sections 61/83 make the ledger the historical record. The schema is
built around four ideas, each of which exists because the alternative is a
silent data corruption:

**Two tables, two jobs.** ``inventory_transactions`` is an append-only ledger
answering *why* the balance changed; ``inventory_balances`` is a derived read
model answering *what is there now*. Current stock is never computed by summing
the ledger on a request path, and the ledger is never edited to make a balance
look right.

**The grain is enforced by the database, not by convention.**
``inventory_balances`` is unique on ``(company, item, warehouse, location,
batch)``. Two of those columns are nullable, and ``NULL <> NULL`` in SQL, so a
plain unique constraint would let "no location, no batch" be inserted twice and
split one stock position across two rows that nothing ever reconciles. The
unique index therefore keys on ``COALESCE(location_id, <nil uuid>)`` and
``COALESCE(batch_id, <nil uuid>)``. The same expression list is the
``ON CONFLICT`` target of the engine's create-if-missing upsert.

**``available_quantity`` is generated by PostgreSQL.** It is
``GENERATED ALWAYS AS (on_hand - reserved - qc_hold - damaged) STORED``, so it
cannot drift from its inputs the way an application-maintained column always
eventually does, and it can be indexed for "what can I promise?" queries.
Application code never writes it.

**The check constraints are the floor.** Negative on-hand is impossible,
reserved can never exceed on-hand, and allocation is always a subset of
reservation - regardless of which code path, script or console session is
writing. A service-level check can be bypassed; these cannot.

**Valuation is FIFO, and it has its own table.** ``inventory_cost_layers`` holds
one row per inbound movement - the quantity received and the price paid - and an
outbound movement consumes them oldest first, at what they actually cost.
``inventory_cost_consumptions`` records which layers each issue drew on, so the
cost of goods issued is auditable back to the receipt that priced it.
``inventory_balances.average_cost`` survives as a derived display figure over
those layers and is never an independent average of its own. ``stock_value`` is
their sum rounded once at the column's four-place scale - close, not exact; see
the column itself.

Bucket semantics (read this before adding a movement type)
----------------------------------------------------------
``on_hand_quantity`` is what is physically in this warehouse/location/batch.
``reserved_quantity``, ``qc_hold_quantity`` and ``damaged_quantity`` are
*subsets* of it - the stock is present but spoken for, held for inspection, or
unusable - which is exactly what the generated ``available_quantity``
expression asserts by subtracting them.

``in_transit_quantity``, ``job_work_quantity`` and ``scrap_quantity`` are the
opposite: company-owned stock that is **not** physically in this position. It
has left for another warehouse, gone to a job-work vendor, or been set aside as
scrap. They sit outside ``on_hand_quantity`` so that summing them with on-hand
gives total company ownership without double counting.
"""

