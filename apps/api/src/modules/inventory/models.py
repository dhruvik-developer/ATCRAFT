class InventoryBalance(TenantEntity):
    """Current stock at one (company, item, warehouse, location, batch) position."""

    __tablename__ = "inventory_balances"

    # eager_defaults makes SQLAlchemy fetch server-generated values with
    # INSERT/UPDATE ... RETURNING. Without it the generated available_quantity
    # column is expired after every UPDATE, and the next read - typically
    # serialising the response - becomes an async lazy load that raises
    # MissingGreenlet. Same trap as a server-side onupdate; see CLAUDE.md.
    __mapper_args__ = {"eager_defaults": True}  # noqa: RUF012 - SQLAlchemy API

    item_id: Mapped[uuid.UUID] = mapped_column(
        GUID, ForeignKey("items.id", ondelete="RESTRICT"), nullable=False
    )
    warehouse_id: Mapped[uuid.UUID] = mapped_column(
        GUID, ForeignKey("warehouses.id", ondelete="RESTRICT"), nullable=False
    )
    location_id: Mapped[uuid.UUID | None] = mapped_column(
        GUID, ForeignKey("storage_locations.id", ondelete="RESTRICT"), nullable=True
    )
    batch_id: Mapped[uuid.UUID | None] = mapped_column(
        GUID, ForeignKey("stock_batches.id", ondelete="RESTRICT"), nullable=True
    )

    on_hand_quantity: Mapped[Decimal] = mapped_column(
        Quantity, nullable=False, default=Decimal("0"), server_default="0"
    )
    reserved_quantity: Mapped[Decimal] = mapped_column(
        Quantity, nullable=False, default=Decimal("0"), server_default="0"
    )
    allocated_quantity: Mapped[Decimal] = mapped_column(
        Quantity, nullable=False, default=Decimal("0"), server_default="0"
    )
    in_transit_quantity: Mapped[Decimal] = mapped_column(
        Quantity, nullable=False, default=Decimal("0"), server_default="0"
    )
    qc_hold_quantity: Mapped[Decimal] = mapped_column(
        Quantity, nullable=False, default=Decimal("0"), server_default="0"
    )
    damaged_quantity: Mapped[Decimal] = mapped_column(
        Quantity, nullable=False, default=Decimal("0"), server_default="0"
    )
    job_work_quantity: Mapped[Decimal] = mapped_column(
        Quantity, nullable=False, default=Decimal("0"), server_default="0"
    )
    scrap_quantity: Mapped[Decimal] = mapped_column(
        Quantity, nullable=False, default=Decimal("0"), server_default="0"
    )

    #: GENERATED ALWAYS AS ... STORED. Never assigned by application code - the
    #: database computes it, so it cannot disagree with its own inputs.
    available_quantity: Mapped[Decimal] = mapped_column(
        Quantity,
        Computed(
            "on_hand_quantity - reserved_quantity - qc_hold_quantity - damaged_quantity",
            persisted=True,
        ),
        nullable=False,
    )

    # --- valuation ----------------------------------------------------------
    # FIFO, held in ``inventory_cost_layers``. These two columns are the read
    # model over those layers: every posting recomputes them from the layers it
    # just opened or consumed, and nothing else may write them.
    #
    # ``average_cost`` is kept because it is what a stock report means by "cost
    # per unit" and four things outside this module read it - but it is now a
    # DERIVED display figure, ``stock_value / on_hand_quantity``, never an
    # independent moving average. Carrying an average that was maintained by its
    # own arithmetic beside a layered valuation would give the codebase two
    # answers to "what is this worth", and they would drift apart the first time
    # a price moved.
    #
    # ASSUMPTION: an emptied position keeps its last derived cost rather than
    # falling to zero. There are no layers left to derive from, so there is no
    # new information; the previous figure is the position's last known cost and
    # is what an adjustment or a count re-books stock at. ``stock_value`` is
    # zero either way, so nothing on the balance sheet depends on the choice.
    average_cost: Mapped[Decimal] = mapped_column(
        UnitPrice, nullable=False, default=Decimal("0"), server_default="0"
    )
    #: The sum of the open cost layers at this position, added up unrounded and
    #: rounded once at this column's own scale - ``Money`` is ``NUMERIC(18, 4)``,
    #: so four places. Deliberately not ``on_hand x average_cost``, which rounds
    #: the per-unit figure and then multiplies the rounding up by the quantity.
    #:
    #: It is *not* exact and must not be described as exact. A four-place column
    #: cannot hold the product of a four-place quantity and a six-place unit
    #: price, so the residual per position is under half of 0.0001 - and it is
    #: per position, which is why summing the same stock split across two
    #: warehouses can differ from the same stock in one by a fraction of a
    #: paisa. ``inventory.service.to_stock_value`` is the one place that rounds
    #: it; the finance valuation report cross-checks the total back against the
    #: layers themselves so a real drift is visible rather than assumed away.
    stock_value: Mapped[Decimal] = mapped_column(
        Money, nullable=False, default=Decimal("0"), server_default="0"
    )

    last_movement_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    __table_args__ = (
        # The grain. COALESCE, not a plain unique constraint: NULL <> NULL would
        # let "no location, no batch" be inserted twice and split one position
        # across two rows. This index is also the ON CONFLICT target of the
        # engine's create-if-missing upsert - see BALANCE_GRAIN_SQL.
        Index(
            "uq_inventory_balances_grain",
            "company_id",
            "item_id",
            "warehouse_id",
            text(f"coalesce(location_id, '{GRAIN_NULL_SENTINEL}'::uuid)"),
            text(f"coalesce(batch_id, '{GRAIN_NULL_SENTINEL}'::uuid)"),
            unique=True,
        ),
        # "Stock of this item everywhere" - the item summary and ATP queries.
        Index("ix_inventory_balances_item", "company_id", "item_id"),
        # "Everything in this warehouse" - the stock list screen.
        Index("ix_inventory_balances_warehouse", "company_id", "warehouse_id", "item_id"),
        # Partial: promising stock only ever looks at positions that have some,
        # which keeps this index a fraction of the table on a mature item master.
        Index(
            "ix_inventory_balances_available",
            "company_id",
            "item_id",
            "warehouse_id",
            postgresql_where=text("available_quantity > 0"),
        ),
        Index("ix_inventory_balances_batch", "company_id", "batch_id"),
        # --- the correctness floor (database contract section 4.3) ----------
        CheckConstraint("on_hand_quantity >= 0", name="on_hand_non_negative"),
        CheckConstraint("reserved_quantity >= 0", name="reserved_non_negative"),
        CheckConstraint("allocated_quantity >= 0", name="allocated_non_negative"),
        CheckConstraint("qc_hold_quantity >= 0", name="qc_hold_non_negative"),
        CheckConstraint("reserved_quantity <= on_hand_quantity", name="reserved_within_on_hand"),
        CheckConstraint(
            "allocated_quantity <= reserved_quantity", name="allocated_within_reserved"
        ),
        # The remaining pools get the same floor. A negative "damaged" or
        # "in transit" is meaningless and would silently inflate availability or
        # company-owned totals.
        CheckConstraint("damaged_quantity >= 0", name="damaged_non_negative"),
        CheckConstraint("in_transit_quantity >= 0", name="in_transit_non_negative"),
        CheckConstraint("job_work_quantity >= 0", name="job_work_non_negative"),
        CheckConstraint("scrap_quantity >= 0", name="scrap_non_negative"),
        CheckConstraint("average_cost >= 0", name="average_cost_non_negative"),
        CheckConstraint("stock_value >= 0", name="stock_value_non_negative"),
    )


