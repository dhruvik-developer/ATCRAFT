class InventoryCostLayer(TenantEntity):
    """One receipt's worth of stock, at what that receipt actually cost.

    This table is what makes the valuation FIFO rather than an average. Every
    movement that adds to ``on_hand_quantity`` opens a layer carrying the
    quantity received and the unit cost paid; every movement that takes stock
    out consumes layers **oldest first**, and the cost of what left is whatever
    those layers really cost. Nothing is re-averaged, so a rising-price series
    leaves the newest, dearest goods on the shelf - which is the whole point of
    the method, and the observable difference from the weighted average this
    replaced.

    Grain
    -----
    A layer belongs to exactly one stock position. ``balance_id`` states that
    directly, which is stronger than repeating the grain columns and hoping the
    two agree: ``inventory_balances`` is already unique on
    ``(company, item, warehouse, location, batch)`` - the COALESCE-based index
    above - so a foreign key to that row *is* the grain, and no position can
    ever consume a neighbouring position's layers. The four grain columns are
    carried as well, written from the same balance row, because stock ageing and
    layer reporting group by item and warehouse and should not have to join to
    do it; ``ix_inventory_cost_layers_grain`` mirrors the balance's own index
    expression so those reads land on the same shape of key.

    Ordering
    --------
    FIFO is meaningless without a **total** order, and ``received_at`` alone is
    not one: PostgreSQL's ``now()`` is transaction *start* time, so every layer
    opened by one multi-line document carries an identical timestamp. Ordering
    by it alone would consume them in an arbitrary sequence, and two runs of the
    same document could cost the same issue differently. The UUIDv7 primary key
    is the tiebreaker - it is monotonic, so ``(received_at, id)`` recovers true
    insertion order within a tie (CLAUDE.md, "created_at ties within a
    transaction").

    ``received_at`` is *business* time - the movement's ``occurred_at`` - not
    system time, so a receipt keyed two days late is consumed in the order the
    goods actually arrived.

    Exhaustion
    ----------
    A layer whose ``remaining_quantity`` reaches zero is **exhausted, not
    deleted**. It is history: ``inventory_cost_consumptions`` references it, and
    it is the evidence for what a past issue cost. The partial index keeps the
    FIFO scan on the open ones only, so an exhausted layer costs nothing to
    carry.
    """

    __tablename__ = "inventory_cost_layers"

    # Same reason as InventoryBalance: this row is UPDATEd on every consumption,
    # and an expired attribute read during response serialisation is the
    # MissingGreenlet trap in CLAUDE.md.
    __mapper_args__ = {"eager_defaults": True}  # noqa: RUF012 - SQLAlchemy API

    #: The position this layer belongs to. The grain, stated as a foreign key.
    balance_id: Mapped[uuid.UUID] = mapped_column(
        GUID, ForeignKey("inventory_balances.id", ondelete="RESTRICT"), nullable=False
    )

    # The grain again, denormalised from the balance row it points at, so a
    # layer report can group by item and warehouse without a join. Written only
    # by the engine, always copied from the locked balance row.
    item_id: Mapped[uuid.UUID] = mapped_column(
        GUID, ForeignKey("items.id", ondelete="RESTRICT"), nullable=False
    )
    warehouse_id: Mapped[uuid.UUID] = mapped_column(
        GUID, ForeignKey("warehouses.id", ondelete="RESTRICT"), nullable=False
    )
    location_id: Mapped[uuid.UUID | None] = mapped_column(
        GUID, ForeignKey("storage_locations.id", ondelete="RESTRICT"), nullable=True
    )
    batch_id: Mapped[uuid.UUID | None] = mapped_column(
        GUID, ForeignKey("stock_batches.id", ondelete="RESTRICT"), nullable=True
    )

    #: Business time of the movement that opened this layer. First half of the
    #: FIFO key; ``id`` is the second.
    received_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)

    #: What was booked in. Never changes.
    original_quantity: Mapped[Decimal] = mapped_column(Quantity, nullable=False)
    #: The queue this layer is part of - see :class:`CostLayerPool`. Fixed when
    #: the layer is opened: a scrap layer is never consumed by an ordinary issue
    #: or counted by the on-hand reconciliation, and an on-hand layer is never
    #: drawn by a scrap disposal.
    pool: Mapped[CostLayerPool] = mapped_column(
        StatusEnum(CostLayerPool, 16),
        nullable=False,
        default=CostLayerPool.ON_HAND,
        server_default=CostLayerPool.ON_HAND.value,
    )
    #: What is left to consume. Falls to zero and stays there.
    remaining_quantity: Mapped[Decimal] = mapped_column(Quantity, nullable=False)
    #: What one unit of this layer cost. Never changes - a layer is a fact about
    #: a past receipt, and re-pricing it would rewrite history.
    unit_cost: Mapped[Decimal] = mapped_column(
        UnitPrice, nullable=False, default=Decimal("0"), server_default="0"
    )

    #: The movement that opened the layer. Nullable for the opening layers the
    #: FIFO migration created from pre-existing balances, and for the
    #: reconciliation layer the engine opens when it finds a position whose
    #: layers do not cover its on-hand - neither of those has a movement behind
    #: it, and inventing one would put a row in the ledger that never happened.
    source_transaction_id: Mapped[uuid.UUID | None] = mapped_column(
        GUID,
        ForeignKey(
            "inventory_transactions.id",
            ondelete="RESTRICT",
            name="fk_cost_layers_source_transaction",
        ),
        nullable=True,
    )
    #: Why this layer exists, for the two cases that have no movement behind
    #: them. ``NULL`` for an ordinary receipt.
    origin: Mapped[str | None] = mapped_column(String(24), nullable=True)

    # Declared purely so the unit of work knows the insert order.
    #
    # SQLAlchemy sorts mappers that no relationship connects by their table
    # name, so ``inventory_cost_layers`` and ``inventory_cost_consumptions``
    # both sorted *before* ``inventory_transactions`` and a posting failed on
    # its own foreign key. A many-to-one relationship registers the dependency
    # and the batch is written parent-first.
    #
    # ``lazy="raise"`` because nothing traverses them: the engine holds every
    # row it writes, and a report reaches a movement's layers by id through
    # ``ix_inventory_cost_consumptions_txn``. An accidental lazy load here would
    # be one query per ledger row.
    source_transaction: Mapped[InventoryTransaction | None] = relationship(
        "InventoryTransaction",
        lazy="raise",
        foreign_keys="InventoryCostLayer.source_transaction_id",
    )

    __table_args__ = (
        # The FIFO pick. Partial, because consumption only ever looks at open
        # layers, and ordered so the scan comes back in consumption order
        # without a sort. ``id`` is in the key because it is the tiebreaker that
        # makes the order total.
        Index(
            "ix_inventory_cost_layers_open",
            "company_id",
            "balance_id",
            "received_at",
            "id",
            postgresql_where=text("remaining_quantity > 0"),
        ),
        # The grain, spelled the way inventory_balances spells it, for reports
        # that reach the layers by position rather than by balance id.
        Index(
            "ix_inventory_cost_layers_grain",
            "company_id",
            "item_id",
            "warehouse_id",
            text(f"coalesce(location_id, '{GRAIN_NULL_SENTINEL}'::uuid)"),
            text(f"coalesce(batch_id, '{GRAIN_NULL_SENTINEL}'::uuid)"),
        ),
        # "Which layer did this receipt open?" - the other direction of the
        # traceability the consumption table gives an issue.
        Index("ix_inventory_cost_layers_source", "company_id", "source_transaction_id"),
        CheckConstraint("original_quantity > 0", name="original_quantity_positive"),
        CheckConstraint("remaining_quantity >= 0", name="remaining_non_negative"),
        # A layer cannot give up more than it ever held.
        CheckConstraint(
            "remaining_quantity <= original_quantity", name="remaining_within_original"
        ),
        CheckConstraint("unit_cost >= 0", name="unit_cost_non_negative"),
        CheckConstraint(f"pool IN ({sql_in_list(CostLayerPool)})", name="pool_known"),
        {"comment": "FIFO cost layers. One row per inbound movement, consumed oldest first."},
    )


#: ``origin`` values for the two layers that have no movement behind them: the
#: opening layers the FIFO migration writes from the balances that existed
#: before it, and the layer the engine opens when it meets a position whose
#: layers do not cover its on-hand (see ``MovementEngine._reconcile_layers``).
LAYER_ORIGIN_MIGRATION = "MIGRATION"
LAYER_ORIGIN_RECONCILIATION = "RECONCILIATION"


def fifo_sort_key(layer: InventoryCostLayer) -> tuple[datetime, uuid.UUID]:
    """The total order FIFO consumption runs in.

    Business time first, primary key second. The tiebreaker is not decoration:
    ``received_at`` comes from the movement's ``occurred_at``, and every layer a
    multi-line goods receipt opens carries the *same* one. Sorting on the
    timestamp alone would hand back those layers in whatever order the database
    felt like, so the same document could cost the same issue two different ways
    on two different runs. The UUIDv7 primary key is monotonic, so it recovers
    the order the layers were really opened in (CLAUDE.md, "created_at ties
    within a transaction" - the trap bites FIFO harder than anything else).

    A naive ``received_at`` is read as UTC rather than refused: every writer in
    the system stamps an aware value, and a sort is the wrong place to discover
    that one did not - it would raise ``TypeError`` in the middle of a posting.
    """
    received = layer.received_at
    if received.tzinfo is None:  # pragma: no cover - defensive; writers stamp UTC
        received = received.replace(tzinfo=UTC)
    return (received, layer.id)


class InventoryCostLayerConsumption(ImmutableLedgerEntity):
    """What one outbound movement took from one cost layer, and what it cost.

    Append-only, like the stock ledger it hangs off. Together these rows are the
    cost of goods issued, broken down by the receipt each unit came from: an
    issue of 30 against layers of 20 @ 100 and 50 @ 120 writes two rows, and the
    30 units cost 3 200 rather than 30 times some average nobody can point at.

    It is not bookkeeping for its own sake. Three things read it:

    * the cost of an issue, auditable back to the receipt that priced it;
    * a stock transfer's inbound leg, which re-opens the *same* costs at the
      destination so moving a box between two of the company's own warehouses
      cannot change what the company's stock is worth;
    * "which receipt did this issue draw on?", the valuation half of the
      traceability the batch and serial tables give the physical goods.
    """

    __tablename__ = "inventory_cost_consumptions"

    transaction_id: Mapped[uuid.UUID] = mapped_column(
        GUID,
        ForeignKey(
            "inventory_transactions.id",
            ondelete="RESTRICT",
            name="fk_cost_consumptions_transaction",
        ),
        nullable=False,
    )
    layer_id: Mapped[uuid.UUID] = mapped_column(
        GUID,
        ForeignKey(
            "inventory_cost_layers.id",
            ondelete="RESTRICT",
            name="fk_cost_consumptions_layer",
        ),
        nullable=False,
    )

    quantity: Mapped[Decimal] = mapped_column(Quantity, nullable=False)
    #: The layer's cost, copied at consumption time. A layer's ``unit_cost``
    #: never changes, so this is a convenience rather than a snapshot - but it
    #: keeps the cost of an issue readable without a join, which is what the
    #: transfer's inbound leg and the costing reports both want.
    unit_cost: Mapped[Decimal] = mapped_column(
        UnitPrice, nullable=False, default=Decimal("0"), server_default="0"
    )
    total_cost: Mapped[Decimal] = mapped_column(
        Money, nullable=False, default=Decimal("0"), server_default="0"
    )

    # Declared purely so the unit of work knows the insert order.
    #
    # SQLAlchemy sorts mappers that no relationship connects by their table
    # name, so ``inventory_cost_layers`` and ``inventory_cost_consumptions``
    # both sorted *before* ``inventory_transactions`` and a posting failed on
    # its own foreign key. A many-to-one relationship registers the dependency
    # and the batch is written parent-first.
    #
    # ``lazy="raise"`` because nothing traverses them: the engine holds every
    # row it writes, and a report reaches a movement's layers by id through
    # ``ix_inventory_cost_consumptions_txn``. An accidental lazy load here would
    # be one query per ledger row.
    transaction: Mapped[InventoryTransaction] = relationship(
        "InventoryTransaction",
        lazy="raise",
        foreign_keys="InventoryCostLayerConsumption.transaction_id",
    )
    layer: Mapped[InventoryCostLayer] = relationship(
        "InventoryCostLayer",
        lazy="raise",
        foreign_keys="InventoryCostLayerConsumption.layer_id",
    )

    __table_args__ = (
        Index("ix_inventory_cost_consumptions_txn", "company_id", "transaction_id"),
        Index("ix_inventory_cost_consumptions_layer", "company_id", "layer_id"),
        CheckConstraint("quantity > 0", name="quantity_positive"),
        CheckConstraint("unit_cost >= 0", name="unit_cost_non_negative"),
        CheckConstraint("total_cost >= 0", name="total_cost_non_negative"),
        {"comment": "Append-only FIFO consumption detail: which layers an issue drew on."},
    )


