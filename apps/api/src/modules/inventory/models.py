class InventoryTransaction(ImmutableLedgerEntity):
    """One stock movement. Append-only: never updated, never deleted.

    A correction is a new, offsetting row - which is why this inherits
    :class:`~src.core.models.ImmutableLedgerEntity` and has no ``updated_at``,
    ``deleted_at`` or version column. ``balance_after`` is stored so a
    reconciliation job can prove the balance table matches the ledger without
    replaying every row.
    """

    __tablename__ = "inventory_transactions"

    transaction_type: Mapped[TransactionType] = mapped_column(
        StatusEnum(TransactionType, 32), nullable=False
    )

    item_id: Mapped[uuid.UUID] = mapped_column(
        GUID, ForeignKey("items.id", ondelete="RESTRICT"), nullable=False
    )
    warehouse_id: Mapped[uuid.UUID] = mapped_column(
        GUID, ForeignKey("warehouses.id", ondelete="RESTRICT"), nullable=False
    )
    location_id: Mapped[uuid.UUID | None] = mapped_column(
        GUID, ForeignKey("storage_locations.id", ondelete="RESTRICT"), nullable=True
    )
    batch_id: Mapped[uuid.UUID | None] = mapped_column(
        GUID, ForeignKey("stock_batches.id", ondelete="RESTRICT"), nullable=True
    )
    serial_id: Mapped[uuid.UUID | None] = mapped_column(
        GUID, ForeignKey("stock_serials.id", ondelete="RESTRICT"), nullable=True
    )

    #: Signed. The sign is imposed by :data:`TRANSACTION_SIGNS`, not by the
    #: caller, so a document cannot express an issue as a negative receipt.
    quantity: Mapped[Decimal] = mapped_column(Quantity, nullable=False)
    unit_cost: Mapped[Decimal] = mapped_column(
        UnitPrice, nullable=False, default=Decimal("0"), server_default="0"
    )
    total_cost: Mapped[Decimal] = mapped_column(
        Money, nullable=False, default=Decimal("0"), server_default="0"
    )
    #: On-hand at this grain immediately after the movement, for reconciliation.
    balance_after: Mapped[Decimal] = mapped_column(Quantity, nullable=False)

    stock_state: Mapped[StockState] = mapped_column(
        StatusEnum(StockState),
        nullable=False,
        default=StockState.AVAILABLE,
        server_default="AVAILABLE",
    )
    #: The pool the quantity came *from*, when the caller named one. NULL means
    #: the transaction type's own default source.
    #:
    #: Without it a ledger row is not self-describing and its effect on
    #: ``on_hand_quantity`` cannot be recomputed: ``SCRAP`` with
    #: ``stock_state=SCRAP`` takes stock out of on-hand when it comes from the
    #: available pool and leaves on-hand untouched when it comes from the
    #: job-work pool, and those two rows are otherwise identical. The
    #: reconciliation identity in ``LedgerRepository.posted_quantity`` depends
    #: on being able to tell them apart.
    source_state: Mapped[StockState | None] = mapped_column(
        StatusEnum(StockState), nullable=True, default=None
    )

    reference_type: Mapped[str] = mapped_column(String(48), nullable=False)
    # Deliberately not a foreign key: the ledger outlives its source document,
    # and purging an archived GRN must not be able to delete stock history.
    reference_id: Mapped[uuid.UUID | None] = mapped_column(GUID, nullable=True)
    reference_code: Mapped[str | None] = mapped_column(String(64), nullable=True)

    #: Never blank in practice - section 83 requires a reason for every movement.
    reason: Mapped[str] = mapped_column(String(255), nullable=False)

    #: Business time. Differs from ``created_at`` when a document is keyed late,
    #: which is normal on a shop floor, so reports date by this column.
    occurred_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)

    __table_args__ = (
        # "Movement history of this item in this warehouse" - the stock card.
        Index(
            "ix_inventory_transactions_item_history",
            "company_id",
            "item_id",
            "warehouse_id",
            text("occurred_at DESC"),
        ),
        # Business-time browsing and date-ranged valuation reports.
        Index(
            "ix_inventory_transactions_occurred",
            "company_id",
            text("occurred_at DESC"),
            text("id DESC"),
        ),
        # Keyset pagination key. src.core.pagination.Cursor encodes
        # (created_at, id), so the ledger endpoint pages on system time even
        # though it reports business time - the two are monotonic together
        # because the primary key is UUIDv7.
        Index(
            "ix_inventory_transactions_keyset",
            "company_id",
            text("created_at DESC"),
            text("id DESC"),
        ),
        # "What did this GRN post?" - the traceability requirement.
        Index(
            "ix_inventory_transactions_reference",
            "company_id",
            "reference_type",
            "reference_id",
        ),
        Index(
            "ix_inventory_transactions_type",
            "company_id",
            "transaction_type",
            text("occurred_at DESC"),
        ),
        Index("ix_inventory_transactions_batch", "company_id", "batch_id"),
        Index("ix_inventory_transactions_serial", "company_id", "serial_id"),
        # A zero-quantity movement records nothing, and would open or consume
        # a cost layer of nothing.
        CheckConstraint("quantity <> 0", name="quantity_non_zero"),
        CheckConstraint("unit_cost >= 0", name="unit_cost_non_negative"),
        {"comment": "Append-only stock ledger. Corrections are offsetting rows, never updates."},
    )


